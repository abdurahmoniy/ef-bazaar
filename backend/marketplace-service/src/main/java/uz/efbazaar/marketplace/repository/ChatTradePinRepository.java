package uz.efbazaar.marketplace.repository;

import org.springframework.data.jpa.repository.JpaRepository;
import org.springframework.data.jpa.repository.Modifying;
import org.springframework.data.jpa.repository.Query;
import org.springframework.data.repository.query.Param;
import uz.efbazaar.marketplace.domain.ChatTradePin;

import java.time.Instant;
import java.util.UUID;

public interface ChatTradePinRepository extends JpaRepository<ChatTradePin, UUID> {

    /**
     * Upserts this trade's pin state for the chat. Last-write-wins on
     * {@code occurredAt} so an out-of-order or redelivered event
     * self-corrects instead of sticking — a delayed {@code trade-opened}
     * arriving after its own {@code trade-closed} must not re-pin.
     *
     * <p>{@code id} is generated by the caller (not {@code uuid_generate_v4()}
     * in SQL) only on the insert branch — {@code ON CONFLICT DO UPDATE} never
     * touches the existing row's id, so a redelivery can't churn the primary
     * key.
     */
    @Modifying(clearAutomatically = true)
    @Query(value = """
            INSERT INTO chat_trade_pins (id, chat_id, trade_id, pinned, occurred_at)
            VALUES (:id, :chatId, :tradeId, :pinned, :occurredAt)
            ON CONFLICT (chat_id, trade_id) DO UPDATE
                SET pinned = EXCLUDED.pinned,
                    occurred_at = EXCLUDED.occurred_at
                WHERE EXCLUDED.occurred_at > chat_trade_pins.occurred_at
            """, nativeQuery = true)
    void upsert(@Param("id") UUID id, @Param("chatId") UUID chatId, @Param("tradeId") UUID tradeId,
               @Param("pinned") boolean pinned, @Param("occurredAt") Instant occurredAt);
}
